"""说给模型听的**收敛与补齐提示**：这几段文案的唯一产地。

## 为什么单独一个模块

`protocol.py` 顶着仓库 2000 行的 ERROR 闸门（`scripts/check_file_length.py`）。这里的东西
与「解析 / 校验 / 接地」三件事都无关 —— 它们只负责把一段话拼出来，不读模型交回来的任何
东西、也不改任何状态。搬出来之后 `protocol.py` 只剩一行回导。

（同样的理由搬过一次：中间轮的字段收窄在 `mid_round.py`。两处的边界画法一样：**能独立
说清一件事的整块才搬**，不要为了凑行数把一个函数切成两半。）

## `build_correction_hint` / `build_channel_mismatch_hint` 为什么**留在 protocol**

它们要用 `looks_like_tool_call_envelope` 与 `_OUTPUT_CHANNEL_FACT`（都在 protocol 里，
且后者的措辞与 protocol 的解析行为绑在一起）。搬过来就得反向导入 protocol，而 protocol
在模块级导入本模块 —— 成环。留在原地是更小的代价。

## 收敛指令的尾巴只许有一份

`_CONVERGE_TAIL` 是「额度耗尽 / 没有额度 / 最后一轮 / 钱快不够 / 探索结束」共用的那一句，
**必须逐字相同**。以前「预算耗尽」那段文案在 `prompt.py` 与 `protocol.py` 里各有一份、
两句话不一样，下场是改一处漏一处 —— 所以它现在只留一份常量，并且与这几份指令同处在一个
文件里。

前四份是**轮首**注入的（这一轮之后还有下一轮，或者这一轮就是循环里的最后一轮）；
第五份 `build_wrap_up_hint` 不同 —— 它发出时**循环已经结束**，是那次补发的兜底调用
（见 `services/ai/wrap_up.py`）。
"""

from __future__ import annotations

from typing import Iterable

# 这几份收敛指令（额度耗尽 / 没有额度 / 最后一轮 / 钱快不够 / 探索结束）共用的尾巴，
# **必须逐字相同**：它管的是**交回来的形态** —— 证据不足的维度要按协议写 hit=false，
# 而不是整段省掉。以前「预算耗尽」那段文案在 prompt 与 protocol 里各有一份、两句话不一样，
# 下场是改一处漏一处；所以这里只留一份常量。
_CONVERGE_TAIL = (
    "对于证据不足的维度，在 dimensions 里写 hit 为 false "
    "并在 note 里说明「信息不足」，同时在报告里标注信息缺口。"
)


def build_baseline_coverage_hint(missing: Iterable[str]) -> str:
    """要求补齐 `baseline_updates` 的那段提示（与其余纠正提示同一处，便于逐字比对）。

    ## 这句话要说清三件事（少一件它就变成一句客套）

    1. **结论照收**：上一轮的 JSON 是**解析成功**的，这一轮只是补一块，不是重写报告 ——
       不说清的话模型重新生成一份正文，两轮的用词会漂移，而平台收的是后一份；
    2. **每条都要给一个状态**，并列出允许的三个值（它上一轮就是漏在这里）；
    3. **为什么值得它花这一轮**：这是旧结论离开「在挂清单」的唯一通道。模型在正文里写
       「已修复」不会有任何作用，下一轮那条还会被送回它面前 —— 这件事它自己看不出来。
    """
    items = tuple(missing)
    listed = "、".join(f"`{item}`" for item in items[:12])
    more = "" if len(items) <= 12 else f" 等 {len(items)} 条"
    return (
        "你上一轮的最终 JSON **解析成功**，但 `baseline_updates` 里缺了第一轮那份历史清单上"
        f"的这几条：{listed}{more}。\n"
        "请**只重发那份完整 JSON**（正文与结论按原样带回来，不要改写、不要压缩），"
        "并为清单上的**每一条**补上一个状态：仍成立写 `standing`，修好了写 `fixed`（附一句"
        "凭什么，在哪次提交、哪个文件的哪一处），被推翻了写 `overturned`。\n"
        "为什么要逐条交代：**这是旧结论离开「在挂清单」的唯一通道** —— 只在正文里写一句"
        "「已修复」，下一轮它还会作为仍然成立的问题被送回来。\n"
    )


def build_budget_exhausted_hint(*, requests_total: int | None = None) -> str:
    """**上下文索取额度**耗尽时注入的收敛指令。

    **不报错退出**——模型手上已有的证据通常够写一份报告了，强制它收敛比作废整轮好。

    ## `requests_total == 0` 要换一句话

    「**用完**了」与「**从来没有**」在模型那里会长成同一句话，而模型会把这句话原样转述
    进报告的信息缺口。项目把上限配成 0 时，它写出来的是「额度用完」，用户据此去查额度
    怎么会被用完 —— 查不到，因为那是配置。所以 0 这一支明说「没有配置额度」。

    **只管索取额度，不管轮次** —— 轮次先耗尽的那一种见 `build_final_round_hint`。
    """
    if requests_total == 0:
        opening = (
            "本次分析**没有配置上下文索取额度**（上限 0 次），读不到任何文件内容、"
            "也做不了跨文件检索。请基于当前已有的证据直接输出 final，禁止请求上下文。"
        )
    else:
        opening = (
            "补充上下文的预算已耗尽。请基于当前已有的证据直接输出 final，"
            "禁止继续请求上下文。"
        )
    return opening + _CONVERGE_TAIL


def build_markdown_reemit_hint() -> str:
    """把上一条 markdown 报告**原样**转成协议 JSON 的纠正提示。

    引擎原先遇到「模型给了 markdown 而不是 JSON」是直接收工的：正文留下来，结构化结论
    整份放弃 —— 哪怕还剩三轮、纠正额度一次没用（实测 run 10 的 S3 跑满 8 轮后写成
    markdown，它负责的 code_logic / version_branch / process 三个维度**一条结构化结论都
    没进清单**；run 6 也出过同一形态）。而「把上一条原样转成 JSON」比「重新写一份报告」
    容易得多：内容已经在对话里，模型只需要换一种包装。

    所以措辞的重心是**不许借机重写**（新增/省略/改写都会让已经写实的证据变形），以及
    只做格式转换、不要再索取上下文。
    """
    return (
        "你上一条回答是一份 **markdown 报告**，而协议要求的是 JSON。"
        "请把**上一条的内容原样**转成协议 JSON（`status` 为 `final`）：结论、证据、影响、"
        "建议都要**逐条搬过来**，不要新增、不要省略、不要趁这次重写或合并。"
        "只输出这个 JSON，不要再索取上下文。" + _CONVERGE_TAIL
    )


def build_final_round_hint(*, round_index: int, max_rounds: int) -> str:
    """**最后一轮**的收敛指令（轮次先耗尽的那一条路）。

    只按索取额度判「该收尾了」是不够的：额度没花完、轮次先到顶，模型就完全不知道
    这是最后一条消息 —— 实测 run 10 的 S3 跑满 8 轮（只用了 38/40 次索取）之后写了一段
    markdown 叙述，而不是协议 JSON：它负责的三个维度（`code_logic` / `version_branch` /
    `process`）**一条结构化结论都没有**，报告里只能按「跑完了但结论没交回」标出来
    （见 `family_ledger._shard_gap_lines`）。同一形态在 run 6 已经出过一次，那次是 5 轮。

    ## 为什么要把机制说给模型听

    模型对「还剩 2 次索取」是有判断力的：不说清，它就会把这 2 次花掉。而**最后一轮索取
    回来的内容要等下一轮才会送到它手上，下一轮不存在** —— 那些内容平台照样去取，只是
    永远到不了模型眼前。所以这里不是客套地让它「收尾」，而是告诉它这件事实：现在索取
    等于白花一轮，且这一轮之后没有任何机会再交结论。
    """
    return (
        f"**这是本次分析的最后一条消息（第 {round_index}/{max_rounds} 轮）。**"
        "你这一轮索取回来的内容要等**下一轮**才会送到你手上，而下一轮不存在 ——"
        "现在再索取等于把这一轮白白花掉：平台会去取，但你永远看不到。"
        "所以本轮必须直接输出 final（按协议给 JSON），不要写成 markdown 叙述。"
        + _CONVERGE_TAIL
    )


def build_token_budget_final_hint() -> str:
    """**钱快不够了**时注入的收敛指令（token 预算先见底的那一条路）。

    ## 为什么这一条必须存在（真机）

    2026-09-26 项目 1 的 run 3：单代理跑了 9 轮、48/50 次索取，**9 轮全在索取上下文、
    一次结论都没写**；第 10 轮开头被 `single_run_budget` 的闸门拦住，整个运行以
    「没有拿到可用的结论」收场 —— 而它当时离上限只差一步，模型却以为轮次还多的是。
    轮次有 `build_final_round_hint`、索取额度有 `build_budget_exhausted_hint`，
    **唯独钱这条在闸门之外一句话都没有**。这一条补的就是它。

    判据是 `SingleRunBudget.next_round_affordable`（把闸门向前推一轮），它的调用点在引擎里 ——
    这一份只负责措辞。

    ## 措辞与另外两条的分别（**不许写成同一句**）

    轮次与索取额度是**硬事实**（「这是最后一条消息」「额度已耗尽」），钱是**估算** ——
    闸门按「已花 + 本轮预留 + 收尾预留 > 上限」判，而单次调用实际花多少只有事后才知道。
    所以这里只说「按你已经花掉的，再要一轮**很可能**就没有下一轮了」。
    模型会把这段话原样抄进报告的信息缺口（`services/ai/round_notes.py` 那一族踩过），
    所以**不许**写成「这是最后一条消息」—— 那会在没到的运行上说一句假话。

    **也不报具体数字**：「已花 1,234,567 / 上限 3,000,000」会被模型原样搬进报告正文，
    而那些是平台的内部账（报告的读者不该看到内部编号与内部额度）。
    """
    return (
        "本次分析的 **token 预算**就要用完了：按你已经花掉的，**再索取一轮很可能就没有"
        "下一轮** —— 那一轮取回来的内容平台照样会去取，但你可能永远看不到。"
        "所以本轮请直接输出 final（按协议给 JSON），把已经看到的证据写完；"
        "确实没查完的按信息缺口如实标注。" + _CONVERGE_TAIL
    )


def build_wrap_up_hint() -> str:
    """**探索已经结束**之后、那次补发调用所带的那条 user 消息（见 `services/ai/wrap_up.py`）。

    ## 它与上面四份「收敛指令」的分别

    那四份都是**轮首**注入的：这一轮跑完之后循环还会转（`build_final_round_hint` 说的
    「这是最后一条消息」也仍然是**探索循环里**的一轮）。这一份不是 —— 它发出时循环已经结束，
    模型这一轮索取什么都不会再被满足（引擎不会再执行任何一次工具调用）。所以措辞的重心
    不是「别浪费这一轮」，而是**把已经看到的写下来**。

    ## 为什么它必须存在（真机）

    2026-09-26 项目 1 的 run 3：9 轮全在索取上下文、一次结论都没写，闸门在第 10 轮开头
    停下，整次运行以「没有拿到可用的结论」收场 —— 而平台手上还留着
    `report_reserve_tokens`（那次 225,000）那笔**报告收尾预留**：它从可花额度里减掉、
    等着被最后写报告的那一次花掉，而原先没有任何一处会去花它。这一份就是那笔钱的用途。

    ## 这里**不许**说「这是最后一条消息」

    那句话在 `build_final_round_hint` 里是硬事实（轮次确实用尽了）。而触发这一份的原因
    可能是钱、可能是轮次、可能是索取额度 —— 说「最后一轮」就是把一个**估算**（钱那条）
    说成事实，模型会把它原样抄进报告的信息缺口（`round_notes` 那一族踩过）。
    这里只说「探索已经结束」这件**确实成立**的事。
    """
    return (
        "本次分析的**探索阶段已经结束**：平台不会再执行任何新的上下文索取，"
        "现在再请求上下文也不会有内容回到你这里。请立刻基于**已经看到的证据**输出 final"
        "（按协议给 JSON）——写清查到了什么、每条结论的证据在哪一处、哪些还没查完。"
        + _CONVERGE_TAIL
    )
